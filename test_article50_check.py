"""Tests for article50-marking-checker (stdlib unittest only).

Fixtures are generated programmatically - no binary blobs in the repo.
"""

import json
import os
import struct
import subprocess
import sys
import tempfile
import unittest
import zlib

import article50_check as a50


def png_chunk(ctype, data):
    return (struct.pack(">I", len(data)) + ctype + data
            + struct.pack(">I", zlib.crc32(ctype + data) & 0xFFFFFFFF))


def make_png(extra_chunks=()):
    ihdr = struct.pack(">IIBBBBB", 1, 1, 8, 2, 0, 0, 0)
    raw = b"\x00\xff\x00\x00"  # 1px scanline
    idat = zlib.compress(raw)
    body = (png_chunk(b"IHDR", ihdr) + b"".join(extra_chunks)
            + png_chunk(b"IDAT", idat) + png_chunk(b"IEND", b""))
    return article50_check_PNG_MAGIC + body


article50_check_PNG_MAGIC = b"\x89PNG\r\n\x1a\n"


def make_jpeg(segments=()):
    out = b"\xff\xd8"
    for marker, payload in segments:
        out += b"\xff" + bytes([marker]) + struct.pack(">H", len(payload) + 2) + payload
    return out + b"\xff\xd9"


class TestFixtures(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        d = self.tmp.name

        # PNG with fake C2PA JUMBF box -> must PASS
        jumb = png_chunk(b"jumb", b"\x00\x00\x00\x10jumb" + b"JUMBF c2pa manifest")
        self.png_c2pa = os.path.join(d, "c2pa.png")
        open(self.png_c2pa, "wb").write(make_png([jumb]))

        # PNG without any marking -> must FAIL
        self.png_plain = os.path.join(d, "plain.png")
        open(self.png_plain, "wb").write(make_png())

        # PNG with tEXt AI marker only -> PASS (weak)
        text = b"Software\x00Generated with AI - ai-generated content"
        self.png_text = os.path.join(d, "marked.png")
        open(self.png_text, "wb").write(make_png([png_chunk(b"tEXt", text)]))

        # JPEG with APP11 JUMBF segment -> must PASS
        app11 = b"Common JUMBF\x00" + b"jumd c2pa data"
        self.jpg_c2pa = os.path.join(d, "c2pa.jpg")
        open(self.jpg_c2pa, "wb").write(make_jpeg([(0xEB, app11)]))

        # Plain JPEG -> must FAIL
        self.jpg_plain = os.path.join(d, "plain.jpg")
        open(self.jpg_plain, "wb").write(make_jpeg())

        # Text with disclosure header -> must PASS
        self.txt_marked = os.path.join(d, "marked.txt")
        open(self.txt_marked, "w").write(
            "X-AI-Generated: true\n"
            "Content-Credentials: c2pa\n"
            "\nThis image was generated by AI.\n")

        # Text without any marker -> must FAIL
        self.txt_plain = os.path.join(d, "plain.txt")
        open(self.txt_plain, "w").write("Just a normal readme file.\n")

    def tearDown(self):
        self.tmp.cleanup()

    # -- PNG --------------------------------------------------------------
    def test_png_with_c2pa_jumbf_passes(self):
        r = a50.check_file(self.png_c2pa)
        self.assertEqual(r["status"], "PASS")
        kinds = [f["kind"] for f in r["findings"]]
        self.assertIn("c2pa-jumbf-box", kinds)

    def test_png_without_marking_fails(self):
        r = a50.check_file(self.png_plain)
        self.assertEqual(r["status"], "FAIL")

    def test_png_text_chunk_marker_passes_weak(self):
        r = a50.check_file(self.png_text)
        self.assertTrue(r["status"].startswith("PASS"))

    # -- JPEG -------------------------------------------------------------
    def test_jpeg_with_jumbf_passes(self):
        r = a50.check_file(self.jpg_c2pa)
        self.assertEqual(r["status"], "PASS")
        kinds = [f["kind"] for f in r["findings"]]
        self.assertIn("c2pa-jumbf-segment", kinds)

    def test_jpeg_without_marking_fails(self):
        r = a50.check_file(self.jpg_plain)
        self.assertEqual(r["status"], "FAIL")

    # -- Text -------------------------------------------------------------
    def test_text_with_disclosure_header_passes(self):
        r = a50.check_file(self.txt_marked)
        self.assertEqual(r["status"], "PASS")
        kinds = [f["kind"] for f in r["findings"]]
        self.assertIn("disclosure-marker", kinds)

    def test_text_without_marker_fails(self):
        r = a50.check_file(self.txt_plain)
        self.assertEqual(r["status"], "FAIL")

    # -- Duty mapping ------------------------------------------------------
    def test_duties_map_to_article50(self):
        r = a50.check_file(self.png_c2pa)
        joined = " ".join(r["duties"])
        self.assertIn("50(2)", joined)
        self.assertIn("50(4)", joined)
        r2 = a50.check_file(self.png_plain)
        self.assertIn("50(2)", " ".join(r2["duties"]))

    # -- CLI ---------------------------------------------------------------
    def test_cli_text_output_and_exit_code(self):
        proc = subprocess.run(
            [sys.executable, "article50_check.py",
             self.png_c2pa, self.png_plain, self.txt_marked, self.txt_plain],
            capture_output=True, text=True, timeout=60)
        self.assertEqual(proc.returncode, 1)  # at least one FAIL
        self.assertIn("ARTICLE 50", proc.stdout)
        self.assertIn("c2pa.png", proc.stdout)

    def test_cli_json_output(self):
        proc = subprocess.run(
            [sys.executable, "article50_check.py", "--json", self.txt_marked],
            capture_output=True, text=True, timeout=60)
        self.assertEqual(proc.returncode, 0)
        doc = json.loads(proc.stdout)
        self.assertEqual(doc["results"][0]["status"], "PASS")

    def test_cli_all_pass_exit_zero(self):
        proc = subprocess.run(
            [sys.executable, "article50_check.py",
             self.png_c2pa, self.jpg_c2pa, self.txt_marked],
            capture_output=True, text=True, timeout=60)
        self.assertEqual(proc.returncode, 0)


if __name__ == "__main__":
    unittest.main()
