"""
article50-marking-checker
=========================
EU AI Act Article 50 machine-readable marking compliance checker.

Checks files for machine-readable AI-generated content markings:

  Images (PNG/JPEG):
    (a) C2PA manifest presence - scans for JUMBF/C2PA box signatures
        (PNG: "jumb" box; JPEG: APP11 "JUMBF"/"Common JUMBF" segments)
    (b) Embedded watermark/metadata flags - PNG tEXt/iTXt chunks and
        JPEG COM/APP segments scanned for AI-generation markers
        ("ai-generated", "c2pa", "synthetic", generator tags, ...)

  Text files:
    (c) Machine-readable disclosure headers/markers
        (e.g. "X-AI-Generated", "AI-GENERATED-CONTENT", content-credentials
        style headers, Article 50 references)

Each finding maps to an Article 50 duty:
  - Art. 50(2): providers of AI systems generating synthetic content must
    embed machine-readable markings (watermarks/metadata).
  - Art. 50(4): deployers publishing AI-generated/manipulated content
    (deepfakes) must disclose it in a machine-readable way.

Deadline context: transparency obligations for providers of certain AI
systems apply from 2 August 2026; the legacy-system grace period for
Article 50 marking of generative AI systems already on the market ends
2 December 2026.

Usage:
    python3 article50_check.py file1.png file2.jpg notes.txt
    python3 article50_check.py --json assets/
"""

import argparse
import json
import os
import struct
import sys

# ---------------------------------------------------------------------------
# Marker keyword lists
# ---------------------------------------------------------------------------
AI_MARKER_KEYWORDS = [
    b"ai-generated", b"ai_generated", b"aigenerated",
    b"synthetic", b"generated by ai", b"machine-generated",
    b"c2pa", b"content credentials", b"content-credentials",
    b"jumbf", b"watermark",
]

GENERATOR_TAGS = [
    b"dall-e", b"midjourney", b"stable diffusion", b"firefly",
    b"gpt-image", b"imagen", b"veo ", b"sora", b"leonardo",
    b"adobe firefly", b"generated with", b"created with ai",
]

TEXT_DISCLOSURE_MARKERS = [
    "x-ai-generated", "ai-generated-content", "ai-generated:",
    "content-credentials", "c2pa", "synthetic-media",
    "machine-readable disclosure", "article 50",
    "this content was generated by ai", "ai generated",
    "deepfake disclosure", "<!-- ai-generated",
]


def _contains_marker(blob, keywords):
    lowered = blob.lower()
    return [kw.decode("utf-8", "replace") for kw in keywords if kw in lowered]


# ---------------------------------------------------------------------------
# PNG parsing
# ---------------------------------------------------------------------------
PNG_MAGIC = b"\x89PNG\r\n\x1a\n"


def parse_png_chunks(data):
    """Yield (chunk_type, chunk_data) for a PNG byte string."""
    chunks = []
    if data[:8] != PNG_MAGIC:
        return chunks
    pos = 8
    while pos + 8 <= len(data):
        length = struct.unpack(">I", data[pos:pos + 4])[0]
        ctype = data[pos + 4:pos + 8]
        cdata = data[pos + 8:pos + 8 + length]
        chunks.append((ctype, cdata))
        pos += 12 + length
        if ctype == b"IEND":
            break
    return chunks


def check_png(data):
    findings = []
    text_chunks = []
    jumbf_box = False
    for ctype, cdata in parse_png_chunks(data):
        if ctype == b"jumb":
            jumbf_box = True
            findings.append(("c2pa-jumbf-box",
                             "PNG 'jumb' (JUMBF/C2PA) box present"))
        if ctype in (b"tEXt", b"iTXt", b"zTXt"):
            text_chunks.append(cdata)
    blob = b"\x00".join(text_chunks)
    for kw in _contains_marker(blob, AI_MARKER_KEYWORDS):
        findings.append(("ai-marker-keyword",
                         f"PNG text chunk contains marker '{kw}'"))
    for tag in _contains_marker(blob, GENERATOR_TAGS):
        findings.append(("generator-tag",
                         f"PNG text chunk contains generator tag '{tag}'"))
    if not data[:8] == PNG_MAGIC:
        findings.append(("not-a-png", "Not a valid PNG file"))
    return findings


# ---------------------------------------------------------------------------
# JPEG parsing
# ---------------------------------------------------------------------------
def check_jpeg(data):
    findings = []
    if data[:2] != b"\xff\xd8":
        findings.append(("not-a-jpeg", "Not a valid JPEG file"))
        return findings
    pos = 2
    segments = []  # (marker, payload)
    while pos + 4 <= len(data):
        if data[pos] != 0xFF:
            break
        marker = data[pos + 1]
        if marker == 0xD9:  # EOI
            break
        if marker == 0xDA:  # SOS: rest is entropy-coded; scan tail raw
            segments.append((marker, data[pos:]))
            break
        if 0xD0 <= marker <= 0xD7 or marker in (0x01,):
            pos += 2
            continue
        seg_len = struct.unpack(">H", data[pos + 2:pos + 4])[0]
        payload = data[pos + 4:pos + 2 + seg_len]
        segments.append((marker, payload))
        pos += 2 + seg_len

    for marker, payload in segments:
        up = payload.upper()
        if marker == 0xEB and (b"JUMBF" in up or b"COMMON JUMBF" in up):
            findings.append(("c2pa-jumbf-segment",
                             "JPEG APP11 JUMBF/C2PA segment present"))
        if b"JUMD" in up or b"C2PA" in up:
            findings.append(("c2pa-signature",
                             "JPEG segment contains C2PA/JUMD signature"))
        if marker in (0xFE, 0xE0, 0xE1):  # COM / APP0 / APP1
            for kw in _contains_marker(payload, AI_MARKER_KEYWORDS):
                findings.append(("ai-marker-keyword",
                                 f"JPEG segment 0x{marker:02X} contains marker '{kw}'"))
            for tag in _contains_marker(payload, GENERATOR_TAGS):
                findings.append(("generator-tag",
                                 f"JPEG segment 0x{marker:02X} contains generator tag '{tag}'"))
    return findings


# ---------------------------------------------------------------------------
# Text files
# ---------------------------------------------------------------------------
def check_text(data):
    findings = []
    try:
        text = data.decode("utf-8", errors="strict")
    except UnicodeDecodeError:
        try:
            text = data.decode("latin-1")
        except Exception:
            return [("undecodable", "Could not decode text")]
    lowered = text.lower()
    for marker in TEXT_DISCLOSURE_MARKERS:
        if marker in lowered:
            findings.append(("disclosure-marker",
                             f"Machine-readable disclosure marker '{marker}'"))
    return findings


# ---------------------------------------------------------------------------
# Verdict logic
# ---------------------------------------------------------------------------
def verdict_for(findings):
    """Map findings -> (status, duties)."""
    hard_pass = any(kind in ("c2pa-jumbf-box", "c2pa-jumbf-segment",
                             "c2pa-signature", "disclosure-marker")
                    for kind, _ in findings)
    soft_pass = any(kind in ("ai-marker-keyword", "generator-tag")
                    for kind, _ in findings)
    if hard_pass:
        return ("PASS",
                ["Art. 50(2) provider machine-readable marking",
                 "Art. 50(4) deployer disclosure (if published)"],
                "Strong machine-readable marking found (C2PA/JUMBF or disclosure header).")
    if soft_pass:
        return ("PASS (weak)",
                ["Art. 50(2) provider machine-readable marking (partial)"],
                "Only keyword/generator metadata found - consider adding C2PA manifest.")
    return ("FAIL",
            ["Art. 50(2) provider machine-readable marking",
             "Art. 50(4) deployer disclosure (if published)"],
            "No machine-readable AI marking detected.")


def check_file(path):
    try:
        with open(path, "rb") as fh:
            data = fh.read()
    except OSError as exc:
        return {"file": path, "status": "ERROR",
                "duties": [], "note": f"Cannot read file: {exc}",
                "findings": []}
    ext = os.path.splitext(path)[1].lower()
    if ext == ".png":
        raw = check_png(data)
    elif ext in (".jpg", ".jpeg"):
        raw = check_jpeg(data)
    else:
        raw = check_text(data)
    findings = [{"kind": k, "detail": d} for k, d in raw]
    status, duties, note = verdict_for(raw)
    return {"file": path, "status": status, "duties": duties,
            "note": note, "findings": findings}


def iter_files(paths):
    for p in paths:
        if os.path.isdir(p):
            for root, _dirs, files in os.walk(p):
                for f in sorted(files):
                    yield os.path.join(root, f)
        else:
            yield p


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Check files for EU AI Act Article 50 machine-readable marking.")
    parser.add_argument("paths", nargs="+", help="Files or directories to check")
    parser.add_argument("--json", action="store_true",
                        help="Machine-readable JSON output")
    args = parser.parse_args(argv)

    results = [check_file(p) for p in iter_files(args.paths)]

    if args.json:
        print(json.dumps({"results": results}, indent=2))
    else:
        print("=" * 70)
        print("EU AI ACT - ARTICLE 50 MARKING CHECK")
        print("=" * 70)
        for r in results:
            print(f"[{r['status']:11}] {r['file']}")
            for f in r["findings"]:
                print(f"              - {f['detail']}")
            print(f"              duties: {'; '.join(r['duties']) or '-'}")
            print(f"              note: {r['note']}")
        print("=" * 70)
        fails = sum(1 for r in results if r["status"] == "FAIL")
        print(f"{len(results)} file(s) checked, {fails} FAIL")

    return 1 if any(r["status"] == "FAIL" for r in results) else 0


if __name__ == "__main__":
    sys.exit(main())
